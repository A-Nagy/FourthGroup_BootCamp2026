using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Csharp_4.Day_6.ThirdCalc
{
     class AllFunctionsClass
    {

        public static double Static_Add(double Num1, double Num2)
        {
            return Num1 + Num2;
        }
        public static double Static_Sub(double Num1, double Num2)
        {
            return Num1 - Num2;
        }
        public static double Static_Multi(double Num1, double Num2)
        {
            return Num1 * Num2;
        }
        public static double Static_Divi(double Num1, double Num2)
        {
            return Num1 / Num2;
        }






    }
}
